"""Сборка системного промпта мастера и истории для нейросети."""

LENGTH_RULES = {
    "short": "Отвечай коротко: 1–2 абзаца. Только самое важное, без длинных описаний.",
    "medium": "Отвечай средне: 2–4 абзаца. Баланс атмосферы и действия.",
    "long": "Отвечай развёрнуто: 4–7 абзацев. Подробные описания мест, NPC, ощущений и деталей.",
}

BASE_RULES = """\
Правила ведения игры:
- Ты описываешь мир, NPC и последствия действий персонажей. Не решай за персонажей игроков: не пиши их реплики, мысли, чувства и действия сверх заявленного.
- За один ход может прийти несколько заявок от разных игроков. Сплети их в одну связную сцену и отреагируй на каждую.
- Отыгрывай NPC живо: у каждого свой голос, мотивы и манера речи. Прямую речь NPC выделяй кавычками-ёлочками «...».
- Держи мир последовательным: не противоречь летописи, установленным фактам и характерам.
- Веди сюжет мягко: используй свои секретные заметки, но давай игрокам свободу. Если они уходят в сторону, пусть мир реагирует естественно.
- Заканчивай ответ ситуацией, которая требует реакции игроков. Не задавай меню вариантов, если игроки сами не просят.
- Сообщения с пометкой [OOC] — разговоры игроков вне игры, а не действия персонажей. Можно коротко ответить на вопрос по правилам, но не продвигай сюжет из-за них.
- Можно использовать **жирный** и *курсив* для акцентов. Не используй заголовки и списки в художественном тексте.
- Пиши по-русски."""

MECHANICS_RULES = """\
Режим: с игровой механикой.
- Когда исход действия неочевиден и важен, не решай его сам. Попроси конкретного игрока сделать бросок, например: «Гермиона, брось /roll 1d20+3 на проверку внимательности».
- Броски делает система, а не ты. Результат придёт сообщением [Бросок]. Никогда не придумывай результаты бросков сам.
- Получив бросок, опиши последствия согласно правилам ниже."""

NARRATIVE_RULES = """\
Режим: повествовательный.
- Не используй кубики, числа и игровые термины. Исходы решай по логике истории, характеру персонажей и драматургии.
- Действия не всегда удаются: неудачи и осложнения делают историю интереснее."""


def _section(title: str, body: str) -> str:
    body = (body or "").strip()
    return f"## {title}\n{body}" if body else ""


def build_system_prompt(settings: dict, characters: list[dict], chronicle: str) -> str:
    chars = "\n".join(
        f"- {c['character']} (игрок {c['player']})" + (f":\n  {c['sheet'].strip()}" if c.get("sheet", "").strip() else "")
        for c in characters
    )
    mode = MECHANICS_RULES if settings.get("mode") == "mechanics" else NARRATIVE_RULES
    if settings.get("mode") == "mechanics" and settings.get("rules", "").strip():
        mode += "\nПравила механики:\n" + settings["rules"].strip()

    sections = [
        "Ты — мастер (ведущий) текстовой ролевой игры для нескольких игроков, которые сидят в общем чате.",
        _section("Мир", settings.get("world", "")),
        _section("Стартовая ситуация", settings.get("situation", "")),
        _section("Секретные заметки мастера о сюжете (игроки их не видят, не раскрывай напрямую)", settings.get("plot", "")),
        _section("Персонажи игроков", chars),
        _section("Стиль и тон", settings.get("style", "")),
        _section("Длина ответа", LENGTH_RULES.get(settings.get("length"), LENGTH_RULES["medium"])),
        _section("Режим игры", mode),
        _section("Летопись кампании (что произошло раньше)", chronicle),
        BASE_RULES,
    ]
    return "\n\n".join(s for s in sections if s)


def format_message(m: dict) -> str:
    kind = m["kind"]
    if kind == "action":
        return f"[{m['character'] or m['author']} (игрок {m['author']})]: {m['content']}"
    if kind == "roll":
        return f"[Бросок] {m['character'] or m['author']}: {m['content']}"
    if kind == "ooc":
        return f"[OOC {m['author']}]: {m['content']}"
    return m["content"]


def build_contents(messages: list[dict]) -> list[dict]:
    """Превращает историю чата в чередующиеся реплики user/model для Gemini."""
    contents: list[dict] = []
    for m in messages:
        if m["kind"] == "system":
            continue
        role = "model" if m["kind"] == "master" else "user"
        text = format_message(m)
        if contents and contents[-1]["role"] == role:
            contents[-1]["parts"][0]["text"] += "\n\n" + text
        else:
            contents.append({"role": role, "parts": [{"text": text}]})

    if not contents:
        contents.append({"role": "user", "parts": [{"text": (
            "[Система]: Игра начинается. Опиши вступительную сцену согласно стартовой ситуации "
            "и представь обстановку так, чтобы каждому персонажу было за что зацепиться."
        )}]})
    else:
        if contents[0]["role"] == "model":
            contents.insert(0, {"role": "user", "parts": [{"text": "[Система]: Игра продолжается."}]})
        if contents[-1]["role"] == "model":
            contents.append({"role": "user", "parts": [{"text": (
                "[Система]: Новых заявок нет, игроки ждут. Продолжи сцену: пусть мир или NPC сделают следующий ход."
            )}]})
    return contents


SUMMARY_SYSTEM = """\
[Летопись] Ты ведёшь летопись текстовой ролевой кампании. Твоя задача — сжать события так, чтобы мастер мог продолжить игру, не перечитывая весь чат.
Сохраняй: ключевые события по порядку, имена NPC и их отношение к героям, найденные предметы и улики, данные обещания и долги, открытые сюжетные нити, важные решения игроков, текущее местоположение и время.
Отбрасывай: стилистические описания, повторы, разговоры вне игры.
Пиши по-русски, сжато, связными абзацами или короткими пунктами."""


def build_summary_request(chronicle: str, messages: list[dict]) -> list[dict]:
    log = "\n\n".join(format_message(m) for m in messages if m["kind"] != "system")
    text = (
        "Составь летопись кампании.\n\n"
        f"Текущая летопись:\n{chronicle.strip() or '(пока пусто)'}\n\n"
        f"Новые события, которые нужно добавить:\n{log}\n\n"
        "Верни обновлённую летопись целиком: старое плюс новое, без лишних вступлений."
    )
    return [{"role": "user", "parts": [{"text": text}]}]
